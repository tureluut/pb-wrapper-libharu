// Regenerate the standalone PureBasic module from the authoritative flat wrapper.
// Usage: node tools/generate_hpdf_module.cjs [--check]
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'hpdf.pbi'), 'utf8').replace(/\r\n/g, '\n');
const publicStart = source.indexOf('; -----------------\n; Constants subset');
const privateStart = source.indexOf('; ----------------------------------------------------------------------------\n; Library load / bind');
const end = source.indexOf('; IDE Options =');
if (publicStart < 0 || privateStart <= publicStart || end <= privateStart) {
  throw new Error('hpdf.pbi layout changed; review the module generator before regenerating.');
}
const diagnostics = [
  'Global HaruBound.i    ; functions successfully bound by HaruInit()',
  'Global HaruMissing$   ; functions that failed to bind ("" = all bound)',
];
let implementation = source.slice(privateStart, end).trimEnd();
for (const declaration of diagnostics) {
  if (!implementation.includes(declaration + '\n')) {
    throw new Error('Diagnostic declaration changed: ' + declaration);
  }
  implementation = implementation.replace(declaration + '\n', '');
}
const helpers = [...implementation.matchAll(/^Procedure(\.[a-z])? (Haru\w+\([^\n]*\))/gm)]
  .map(match => 'Declare' + (match[1] || '') + ' ' + match[2]);
if (helpers.length !== (implementation.match(/^Procedure/gm) || []).length) {
  throw new Error('An implementation procedure was not exported; review the generator.');
}
const indent = text => text.split('\n').map(line => line ? '  ' + line : '').join('\n');
const header = `; ----------------------------------------------------------------------------
; hpdf_module.pbi - standalone HPDF module alternative to hpdf.pbi
; Author / license / ABI / platform requirements: see original header below.
;
; Generated by tools/generate_hpdf_module.cjs; edit hpdf.pbi and regenerate
; to keep the two APIs in sync. No other include is required at compile time.
;
; Public API: HPDF::HaruInit(), HPDF::HPDF_*, HPDF::Haru*,
; HPDF::#HPDF_*, HPDF::HPDFPoint / HPDFRect / HPDFDate,
; HPDF::HaruBound and HPDF::HaruMissing$.
; Library handles, binding macro and per-document caches are private.
; The original names, signatures and lifecycle contract are unchanged:
; initialize once before using function pointers, free all documents using
; HaruFree(), then HaruShutdown(). Calls after shutdown are invalid.
; Can coexist with hpdf.pbi; each wrapper owns its own library/cache state.
; Prefer qualified names over UseModule HPDF when including both wrappers.
; ----------------------------------------------------------------------------

`;
const provenance = source.slice(0, publicStart);
const result = header + provenance + 'DeclareModule HPDF\n  EnableExplicit\n\n' +
  indent(source.slice(publicStart, privateStart).trimEnd()) + '\n\n' +
  indent(diagnostics.join('\n')) + '\n\n' + indent(helpers.join('\n')) +
  '\nEndDeclareModule\n\nModule HPDF\n  EnableExplicit\n\n' +
  indent(implementation) + '\nEndModule\n';
const target = path.join(root, 'hpdf_module.pbi');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== result) {
    console.error('hpdf_module.pbi is out of date; run node tools/generate_hpdf_module.cjs');
    process.exitCode = 1;
  } else {
    console.log('hpdf_module.pbi is in sync with hpdf.pbi');
  }
} else {
  fs.writeFileSync(target, result, 'utf8');
  console.log('Generated hpdf_module.pbi (' + helpers.length + ' helpers)');
}
